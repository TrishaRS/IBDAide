package com.ibdaide.app.core

import android.graphics.Color
import android.graphics.Paint
import android.graphics.Path
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import java.io.ByteArrayOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/** FR-9: on-device PDF doctor report — same content as iOS. */

data class ReportData(
    val patientName: String,
    val diagnosis: String,
    val scoreLabel: String,
    val startDate: Long,
    val endDate: Long,
    val dailyScores: List<Pair<Long, Int>>,
    val totalBMs: Int,
    val bloodDays: Int,
    val avgPain: Double?,
    val adherencePercent: Int?,
    val triggers: List<String>,
    val questions: List<String>,
    val qolTotals: List<Pair<Long, Int>>,
    val includeQoL: Boolean,
)

object PdfReportBuilder {

    private const val PAGE_W = 612
    private const val PAGE_H = 792
    private const val MARGIN = 48f

    fun makePdf(r: ReportData): ByteArray {
        val doc = PdfDocument()
        var page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, 1).create())
        var canvas = page.canvas
        var y = MARGIN
        val df = SimpleDateFormat("MMM d, yyyy", Locale.US)

        val body = Paint().apply { textSize = 12f; color = Color.BLACK; isAntiAlias = true }
        val gray = Paint(body).apply { color = Color.DKGRAY; textSize = 11f }
        val h1 = Paint(body).apply { textSize = 22f; typeface = Typeface.DEFAULT_BOLD }
        val h2 = Paint(body).apply { textSize = 15f; typeface = Typeface.DEFAULT_BOLD }
        val small = Paint(body).apply { textSize = 9f; color = Color.GRAY; typeface = Typeface.create(Typeface.DEFAULT, Typeface.ITALIC) }

        fun newPageIfNeeded(needed: Float) {
            if (y + needed > PAGE_H - MARGIN) {
                doc.finishPage(page)
                page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, doc.pages.size + 1).create())
                canvas = page.canvas
                y = MARGIN
            }
        }

        fun draw(text: String, paint: Paint, spacing: Float = 6f) {
            val maxWidth = PAGE_W - MARGIN * 2
            var remaining = text
            while (remaining.isNotEmpty()) {
                var count = paint.breakText(remaining, true, maxWidth, null)
                if (count < remaining.length) {
                    val lastSpace = remaining.substring(0, count).lastIndexOf(' ')
                    if (lastSpace > 0) count = lastSpace + 1
                }
                newPageIfNeeded(paint.textSize + spacing)
                canvas.drawText(remaining.substring(0, count).trimEnd(), MARGIN, y + paint.textSize, paint)
                y += paint.textSize + 4f
                remaining = remaining.substring(count)
            }
            y += spacing - 4f
        }

        draw("IBD Aide — Health Summary", h1, 8f)
        draw("${r.patientName.ifEmpty { "Patient" }} · ${r.diagnosis}", gray)
        draw("Period: ${df.format(Date(r.startDate))} – ${df.format(Date(r.endDate))}    Generated: ${df.format(Date())}", gray, 14f)

        draw("Symptom summary", h2)
        val scores = r.dailyScores.map { it.second }
        if (scores.isEmpty()) {
            draw("No symptom scores recorded in this period.", body)
        } else {
            val avg = scores.sum().toDouble() / scores.size
            draw("${r.scoreLabel} — avg %.1f, min ${scores.min()}, max ${scores.max()} over ${scores.size} recorded days".format(avg), body)
            newPageIfNeeded(100f)
            drawSparkline(canvas, r.dailyScores, MARGIN, y, PAGE_W - MARGIN * 2, 90f)
            y += 100f
        }
        draw("Bowel movements: ${r.totalBMs} logged · days with visible blood: ${r.bloodDays}", body)
        r.avgPain?.let { draw("Average abdominal pain: %.1f / 10".format(it), body, 14f) }

        draw("Medication adherence", h2)
        draw(r.adherencePercent?.let { "$it% of scheduled doses recorded as taken in this period." }
            ?: "No scheduled medications tracked in this period.", body, 14f)

        draw("Food triggers", h2)
        draw(if (r.triggers.isEmpty()) "None recorded." else r.triggers.joinToString(" · "), body, 14f)

        draw("Questions for this visit", h2)
        if (r.questions.isEmpty()) draw("None.", body, 14f)
        else {
            r.questions.forEachIndexed { i, q -> draw("${i + 1}. $q", body, 3f) }
            y += 10f
        }

        if (r.includeQoL && r.qolTotals.isNotEmpty()) {
            draw("Quality-of-life check-ins (adapted IBD-Control-8; higher = better)", h2)
            r.qolTotals.takeLast(6).forEach { (date, total) -> draw("${df.format(Date(date))}: $total / 32", body, 3f) }
            y += 10f
        }

        draw("Generated by IBD Aide from patient-reported data. Scores are modified, informational adaptations of clinical indices and are not a diagnosis. Not a medical device.", small)

        doc.finishPage(page)
        val out = ByteArrayOutputStream()
        doc.writeTo(out)
        doc.close()
        return out.toByteArray()
    }

    /** Renders with ANY number of points — a single logged day shows as a dot. */
    private fun drawSparkline(canvas: android.graphics.Canvas, points: List<Pair<Long, Int>>,
                              x: Float, y: Float, w: Float, h: Float) {
        if (points.isEmpty()) return
        val values = points.map { it.second.toDouble() }
        val maxV = maxOf(values.max(), 1.0)
        val range = maxOf(maxV, 1.0)

        val border = Paint().apply { style = Paint.Style.STROKE; color = Color.LTGRAY; strokeWidth = 0.5f }
        canvas.drawRect(x, y, x + w, y + h, border)

        val teal = Color.rgb(46, 139, 132)
        fun px(i: Int) = if (values.size == 1) x + w / 2 else x + w * i / (values.size - 1)
        fun py(v: Double) = y + h - (h * (v / range)).toFloat()

        if (values.size > 1) {
            val line = Paint().apply {
                style = Paint.Style.STROKE; strokeWidth = 1.5f; isAntiAlias = true; color = teal
            }
            val path = Path()
            values.forEachIndexed { i, v ->
                if (i == 0) path.moveTo(px(i), py(v)) else path.lineTo(px(i), py(v))
            }
            canvas.drawPath(path, line)
        }
        val dot = Paint().apply { style = Paint.Style.FILL; isAntiAlias = true; color = teal }
        values.forEachIndexed { i, v -> canvas.drawCircle(px(i), py(v), 2.5f, dot) }

        val axis = Paint().apply { textSize = 8f; color = Color.GRAY; isAntiAlias = true }
        canvas.drawText("${maxV.toInt()}", x + 2, y + 9, axis)
        canvas.drawText("0", x + 2, y + h - 2, axis)
    }
}
